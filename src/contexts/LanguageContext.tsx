export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window !== 'undefined') {
      const saved = localStorage.getItem('language') as Language;
      return saved && ['en', 'es', 'pt-br', 'fr'].includes(saved) ? saved : 'en';
    }
    return 'en';
  });

  useEffect(() => {
    if (typeof window !== 'undefined') {
      localStorage.setItem('language', language);
    }
  }, [language]);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
  };

  const t = (key: string): string => {
    const current = translations[language] ?? {};
    const rawValue = current[key];
    const hasValue = typeof rawValue === 'string' && rawValue.trim().length > 0;

    if (hasValue) {
      return rawValue;
    }

    const fallback = translations.en[key];

    if (import.meta.env.DEV) {
      if (fallback !== undefined) {
        // Key exists in EN but not (properly) in current locale (missing or empty)
        // eslint-disable-next-line no-console
        console.warn(`[i18n] Missing translation for "${language}": ${key}`);
      } else {
        // Key missing everywhere
        // eslint-disable-next-line no-console
        console.warn(`[i18n] Missing translation key in all locales: ${key}`);
      }

      // Extra diagnostics for Spanish so we never ship ES with hidden English
      if (language === 'es') {
        const err = new Error();
        const stack = err.stack?.split('\n').slice(2, 5).join(' | ') ?? 'unknown';
        // eslint-disable-next-line no-console
        console.warn(
          `[i18n-missing][es] key=${key} value="${rawValue ?? ''}" fallback="${fallback ?? ''}" source=${stack}`,
        );
      }
    }

    // Fallback to EN when available; otherwise return the key so issues are visible
    return fallback ?? key;
  };

  // Strict translator that never returns raw keys
  const tx = (key: string, options?: any): string => {
    const val = t(key);
    // Check if value is a raw key or contains problematic patterns
    if (!val || val === key || val.includes('.results.') || val.includes('.scaleNote.') || val.includes('profile.results.scaleNote')) {
      if (import.meta.env.DEV) {
        console.error(`[i18n-missing] locale=${language} key=${key} value="${val}"`);
      }
      // Return empty string instead of raw key to avoid UI pollution
      return '';
    }
    // Simple placeholder replacement if options provided
    if (options) {
      return Object.entries(options).reduce((acc, [k, v]) => {
        return acc.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      }, val);
    }
    return val;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, tx }}>
      {children}
    </LanguageContext.Provider>
  );
};

// Export raw translations for tooling (e.g. i18n audit). Not used directly by UI.
export const rawTranslations = translations;

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within LanguageProvider');
  }
  return context;
};

